export function namePool(born: number, sex: Sex): readonly string[] {
  const era = nameEras.find(e => born < e.before)!;
  return sex === '남' ? era.male : era.female;
}

// `roll` is the engine's single random draw for this name. Names already used by living
// people or by anyone born in the last 60 years are skipped deterministically (no extra
// random draws), so siblings, cousins and twins rarely share a full name.
export function givenName(
  roll: number,
  surname: string,
  born: number,
  sex: Sex,
  taken: ReadonlySet<string>,
): string {
  const pool = namePool(born, sex),
    start = Math.floor(roll * pool.length);
  for (let k = 0; k < pool.length; k++) {
    const full = surname + pool[(start + k) % pool.length];
    if (!taken.has(full)) return full;
  }
  return surname + pool[start];
}
